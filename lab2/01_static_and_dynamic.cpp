#include <iostream>
using namespace std;

// ===== ПРОСТОЙ КЛАСС =====
class Point {
public:
    double x;
    double y;
    
    Point() {
        x = 0;
        y = 0;
        cout << "[Point] Конструктор без параметров: x=" << x << ", y=" << y << endl;
    }
    
    Point(double px, double py) {
        x = px;
        y = py;
        cout << "[Point] Конструктор с параметрами: x=" << x << ", y=" << y << endl;
    }
    
    void display() {
        cout << "  Точка: (" << x << ", " << y << ")" << endl;
    }
};

// ===== ДЕМОНСТРАЦИЯ =====
int main() {
    cout << "========== СТАТИЧЕСКИЕ И ДИНАМИЧЕСКИЕ ОБЪЕКТЫ ==========" << endl;
    
    // 1. СТАТИЧЕСКИЙ ОБЪЕКТ (создан в стеке)
    cout << "\n1. СТАТИЧЕСКИЙ ОБЪЕКТ (автоматическое управление памятью):" << endl;
    cout << "   Команда: Point p1;" << endl;
    Point p1;
    cout << "   После создания:" << endl;
    p1.display();
    
    // 2. СТАТИЧЕСКИЙ ОБЪЕКТ С ПАРАМЕТРАМИ
    cout << "\n2. СТАТИЧЕСКИЙ ОБЪЕКТ С ПАРАМЕТРАМИ:" << endl;
    cout << "   Команда: Point p2(3.5, 4.2);" << endl;
    Point p2(3.5, 4.2);
    cout << "   После создания:" << endl;
    p2.display();
    
    // 3. ОБРАЩЕНИЕ К АТРИБУТАМ СТАТИЧЕСКОГО ОБЪЕКТА
    cout << "\n3. ОБРАЩЕНИЕ К АТРИБУТАМ СТАТИЧЕСКОГО ОБЪЕКТА:" << endl;
    cout << "   p1.x = " << p1.x << endl;
    cout << "   p1.y = " << p1.y << endl;
    cout << "   Изменям значения:" << endl;
    p1.x = 10;
    p1.y = 20;
    cout << "   После изменения:" << endl;
    p1.display();
    
    // 4. ДИНАМИЧЕСКИЙ ОБЪЕКТ (создан в куче)
    cout << "\n4. ДИНАМИЧЕСКИЙ ОБЪЕКТ (ручное управление памятью):" << endl;
    cout << "   Команда: Point *p3 = new Point();" << endl;
    Point *p3 = new Point();
    cout << "   Адрес объекта в памяти: " << p3 << endl;
    cout << "   После создания:" << endl;
    p3->display();
    
    // 5. ДИНАМИЧЕСКИЙ ОБЪЕКТ С ПАРАМЕТРАМИ
    cout << "\n5. ДИНАМИЧЕСКИЙ ОБЪЕКТ С ПАРАМЕТРАМИ:" << endl;
    cout << "   Команда: Point *p4 = new Point(7.5, 8.9);" << endl;
    Point *p4 = new Point(7.5, 8.9);
    cout << "   Адрес объекта в памяти: " << p4 << endl;
    cout << "   После создания:" << endl;
    p4->display();
    
    // 6. ОБРАЩЕНИЕ К АТРИБУТАМ ДИНАМИЧЕСКОГО ОБЪЕКТА
    cout << "\n6. ОБРАЩЕНИЕ К АТРИБУТАМ ДИНАМИЧЕСКОГО ОБЪЕКТА:" << endl;
    cout << "   Через оператор -> (для указателя):" << endl;
    cout << "   p4->x = " << p4->x << endl;
    cout << "   p4->y = " << p4->y << endl;
    cout << "   Или через разыменование: (*p4).x = " << (*p4).x << endl;
    cout << "   Изменям значения:" << endl;
    p4->x = 15;
    p4->y = 25;
    cout << "   После изменения:" << endl;
    p4->display();
    
    // 7. СРАВНЕНИЕ АДРЕСОВ
    cout << "\n7. СРАВНЕНИЕ АДРЕСОВ:" << endl;
    cout << "   Адрес p1 (статический): " << &p1 << " (в стеке)" << endl;
    cout << "   Адрес p2 (статический): " << &p2 << " (в стеке)" << endl;
    cout << "   Адрес p3 (динамический): " << p3 << " (в куче)" << endl;
    cout << "   Адрес p4 (динамический): " << p4 << " (в куче)" << endl;
    
    // 8. УДАЛЕНИЕ ДИНАМИЧЕСКИХ ОБЪЕКТОВ
    cout << "\n8. УДАЛЕНИЕ ДИНАМИЧЕСКИХ ОБЪЕКТОВ:" << endl;
    cout << "   Команда: delete p3;" << endl;
    delete p3;
    cout << "   Объект удален из памяти" << endl;
    p3 = nullptr;  // Хорошая практика - обнулить указатель
    cout << "   p3 = nullptr; (защита от double-delete)" << endl;
    
    cout << "   Команда: delete p4;" << endl;
    delete p4;
    cout << "   Объект удален из памяти" << endl;
    p4 = nullptr;
    
    // 9. СТАТИЧЕСКИЕ ОБЪЕКТЫ УДАЛЯЮТСЯ АВТОМАТИЧЕСКИ
    cout << "\n9. КОНЕЦ ПРОГРАММЫ - СТАТИЧЕСКИЕ ОБЪЕКТЫ УДАЛЯЮТСЯ АВТОМАТИЧЕСКИ:" << endl;
    cout << "   p1 и p2 будут удалены автоматически" << endl;
    
    return 0;
}

/*
КЛЮЧЕВЫЕ РАЗЛИЧИЯ:

СТАТИЧЕСКИЙ ОБЪЕКТ:
- Создание: Point p1;
- Память: стек
- Сколько живёт: до конца блока (автоматически)
- Адрес: &p1 (оператор &)
- Обращение: p1.attribute или p1.method()
- Удаление: автоматическое
- Ошибка: нельзя забыть delete (так как автоматическое удаление)

ДИНАМИЧЕСКИЙ ОБЪЕКТ:
- Создание: Point *p = new Point();
- Память: куча
- Сколько живёт: пока не запросишь delete
- Адрес: p (сам указатель уже адрес)
- Обращение: p->attribute или p->method()
- Удаление: ручное (delete)
- Ошибка: можно забыть delete (утечка памяти) или удалить дважды (double-delete)
*/
